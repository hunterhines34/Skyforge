#!/usr/bin/env node
// Builds js/airports-data.js from the public-domain OurAirports database.
// Usage: node tools/build-airports.js   (needs network access)
const fs = require('fs');
const path = require('path');
const BASE = 'https://davidmegginson.github.io/ourairports-data/';

function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else q = false; }
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

(async () => {
  const get = async (f) => (await fetch(BASE + f)).text();
  const [airportsCsv, runwaysCsv] = await Promise.all([get('airports.csv'), get('runways.csv')]);
  const airports = new Map();
  for (const a of parseCsv(airportsCsv)) {
    if (!['large_airport', 'medium_airport', 'small_airport'].includes(a.type)) continue;
    airports.set(a.ident, a);
  }
  const hard = /^(asp|con|pem|bit|tar|asph|conc|paved|mac|pcc|grooved)/i;
  const out = new Map();
  for (const r of parseCsv(runwaysCsv)) {
    const a = airports.get(r.airport_ident);
    if (!a || r.closed === '1') continue;
    const v = ['le_latitude_deg', 'le_longitude_deg', 'he_latitude_deg', 'he_longitude_deg'].map((k) => parseFloat(r[k]));
    if (v.some((n) => !isFinite(n))) continue;
    const len = parseFloat(r.length_ft) * 0.3048;
    if (!(len >= 760) || !hard.test(r.surface || '')) continue;
    const width = Math.max(18, Math.min(80, (parseFloat(r.width_ft) || 100) * 0.3048));
    const fix = (n) => Math.round(n * 1e6) / 1e6;
    if (!out.has(a.ident)) {
      out.set(a.ident, [a.ident, a.name, fix(parseFloat(a.latitude_deg)), fix(parseFloat(a.longitude_deg)),
        Math.round((parseFloat(a.elevation_ft) || 0) * 0.3048), a.type[0], []]);
    }
    out.get(a.ident)[6].push([r.le_ident, r.he_ident, fix(v[0]), fix(v[1]), fix(v[2]), fix(v[3]), Math.round(width), r.lighted === '1' ? 1 : 0]);
  }
  const list = [...out.values()].sort((x, y) => x[0].localeCompare(y[0]));
  const js = '/* Generated by tools/build-airports.js from OurAirports (public domain, https://ourairports.com/data/).\n' +
    ' * [ident, name, lat, lon, elevation_m, size(l/m/s), [[lowEnd, highEnd, leLat, leLon, heLat, heLon, width_m, lighted], ...]] */\n' +
    'window.SKYFORGE_AIRPORTS = ' + JSON.stringify(list) + ';\n';
  fs.writeFileSync(path.resolve(__dirname, '..', 'js', 'airports-data.js'), js);
  console.log(`${list.length} airports, ${list.reduce((n, a) => n + a[6].length, 0)} runways, ${(js.length / 1e6).toFixed(2)} MB`);
})();
